function main() {
  const outputPath = process.argv.includes('--output')
    ? process.argv[process.argv.indexOf('--output') + 1]
    : join(__dirname, '..', '..', '..', 'data', 'staging', 'jee-main-sample.json');

  // Normalize all questions
  const records = rawQuestions.map(raw => normalizeQuestion(raw, sourceInfo));

  // Create the export
  const output = {
    exportedAt: new Date().toISOString(),
    pipeline: 'jeemocks-ingestion-pipeline',
    description: 'Sample JEE Main & Advanced questions for testing the ingestion pipeline',
    sourceSummary: {
      name: sourceInfo.name,
      url: sourceInfo.url,
      legalConfidence: sourceInfo.legalConfidence,
    },
    recordCount: records.length,
    bySubject: {
      PHYSICS: records.filter(r => r.subject === 'PHYSICS').length,
      CHEMISTRY: records.filter(r => r.subject === 'CHEMISTRY').length,
      MATHS: records.filter(r => r.subject === 'MATHS').length,
    },
    records,
  };

  writeFileSync(outputPath, JSON.stringify(output, null, 2), 'utf-8');
  console.log(`✅ Generated ${records.length} sample questions → ${outputPath}`);
  console.log(`   Physics:   ${output.bySubject.PHYSICS}`);
  console.log(`   Chemistry: ${output.bySubject.CHEMISTRY}`);
  console.log(`   Maths:     ${output.bySubject.MATHS}`);
}

main();
